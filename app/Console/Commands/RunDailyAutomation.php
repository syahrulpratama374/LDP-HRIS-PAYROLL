<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use App\Models\PengajuanCuti;
use App\Models\Absensi;
use App\Models\Aset;
use App\Models\Karyawan;
use App\Models\JadwalShiftKaryawan;
use App\Models\Pengumuman;
use Carbon\Carbon;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Log;

class RunDailyAutomation extends Command
{
    // Nama perintah yang akan dipanggil di terminal
    protected $signature = 'ldp:daily-automation {--tanggal= : Tanggal (Y-m-d) yang dievaluasi untuk Alpha; default kemarin}';
    protected $description = 'Menjalankan tugas otomatis harian (Auto-Cuti, Auto-Alpha & Peringatan Pajak Aset)';

    public function handle()
    {
        $hariIni = Carbon::today()->toDateString();

        // ==========================================
        // 1. AUTO-CUTI (Eksekusi Absensi Karyawan)
        // ==========================================
        $cutiBerjalan = PengajuanCuti::with('masterJenisCuti')->where('status_approval', 'Disetujui')
            ->whereDate('tanggal_mulai', '<=', $hariIni)
            ->whereDate('tanggal_selesai', '>=', $hariIni)
            ->get();

        $jumlahCuti = 0;
        foreach ($cutiBerjalan as $cuti) {
            // Cek agar tidak absen ganda di hari yang sama
            $sudahAbsen = Absensi::where('karyawan_id', $cuti->karyawan_id)
                ->whereDate('tanggal', $hariIni)
                ->exists();

            if (!$sudahAbsen) {
                Absensi::create([
                    'karyawan_id' => $cuti->karyawan_id,
                    'tanggal' => $hariIni,
                    'status' => 'Cuti',
                    'catatan' => 'Auto-generated by System: ' . ($cuti->masterJenisCuti->nama_cuti ?? 'Cuti'),
                ]);
                $jumlahCuti++;
            }
        }

        // ==========================================
        // 2. AUTO-ALPHA (karyawan aktif tanpa absensi/cuti di hari kerja)
        // ==========================================
        // Dievaluasi untuk KEMARIN (hari sudah selesai) agar yang belum clock-in
        // pada pukul 00:00 hari ini tidak langsung ditandai Alpha.
        $tanggalAlpha = $this->option('tanggal')
            ? Carbon::parse($this->option('tanggal'))->toDateString()
            : Carbon::yesterday()->toDateString();
        $jumlahAlpha = $this->generateAlpha($tanggalAlpha);

        // ==========================================
        // 3. PERINGATAN PAJAK ASET (H-30)
        // ==========================================
        $hMin30 = Carbon::today()->addDays(30)->toDateString();
        $asetExpired = Aset::whereDate('tgl_expired_pajak', $hMin30)->get();

        $jumlahAset = 0;
        foreach ($asetExpired as $aset) {
            Pengumuman::create([
                'judul' => '🚨 PERINGATAN PAJAK ASET: ' . $aset->kode_aset,
                'konten' => "Pajak/Lisensi untuk aset **{$aset->nama_aset}** ({$aset->kode_aset}) akan habis tempo pada **{$aset->tgl_expired_pajak}**. Mohon tim GA/Admin segera melakukan perpanjangan.",
                'pembuat_id' => 1, // Dibuat otomatis atas nama Super Admin (ID 1)
                'target_audiens' => 'Global', 
                'tgl_mulai' => $hariIni,
                'tgl_selesai' => $hMin30,
                'tipe_banner' => 'Penting',
                'is_aktif' => true,
            ]);
            $jumlahAset++;
        }

        // Catat hasil kerja robot di terminal dan log sistem
        $pesan = "Daily Automation Selesai: {$jumlahCuti} Cuti dieksekusi, {$jumlahAlpha} Alpha dibuat ({$tanggalAlpha}), {$jumlahAset} Peringatan Aset dibuat.";
        $this->info($pesan);
        Log::info($pesan);
    }

    /**
     * Buat absensi 'Alpha' untuk karyawan aktif yang tidak punya absensi maupun cuti
     * Disetujui pada hari kerja. Hari kerja: bukan hari libur nasional/cuti bersama;
     * karyawan shift (departemen wajib logbook) hanya jika terjadwal di roster (tidak ada
     * roster = off shift); karyawan reguler hanya Senin-Jumat.
     */
    private function generateAlpha(string $tanggal): int
    {
        $tgl = Carbon::parse($tanggal);

        if (DB::table('hari_liburs')->whereDate('tanggal', $tanggal)->exists()) {
            return 0;
        }

        $sudahAbsen = Absensi::whereDate('tanggal', $tanggal)->pluck('karyawan_id')->all();
        $sedangCuti = PengajuanCuti::where('status_approval', 'Disetujui')
            ->whereDate('tanggal_mulai', '<=', $tanggal)
            ->whereDate('tanggal_selesai', '>=', $tanggal)
            ->pluck('karyawan_id')->all();
        $terjadwal = JadwalShiftKaryawan::whereDate('tanggal', $tanggal)->pluck('karyawan_id')->all();

        $jumlah = 0;
        Karyawan::with('departemen')
            ->where('status_aktif', true)
            ->whereDate('tgl_bergabung', '<=', $tanggal)
            ->chunkById(200, function ($karyawans) use ($tanggal, $tgl, $sudahAbsen, $sedangCuti, $terjadwal, &$jumlah) {
                foreach ($karyawans as $k) {
                    if (in_array($k->id, $sudahAbsen) || in_array($k->id, $sedangCuti)) {
                        continue;
                    }

                    $isShift = $k->departemen && $k->departemen->is_wajib_logbook;
                    $hariKerja = $isShift ? in_array($k->id, $terjadwal) : $tgl->isWeekday();
                    if (!$hariKerja) {
                        continue;
                    }

                    Absensi::create([
                        'karyawan_id' => $k->id,
                        'tanggal' => $tanggal,
                        'status' => 'Alpha',
                        'catatan' => 'Auto-generated by System: tidak ada absensi/cuti',
                    ]);
                    $jumlah++;
                }
            });

        return $jumlah;
    }
}
